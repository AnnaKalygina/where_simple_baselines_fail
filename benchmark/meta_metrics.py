"""Per-perturbation metric aggregation and the BS / CF headline scores.

Headline outputs
================
* **Baseline Saturation (BS):**
      BS = (m_baseline - m_neg) / (m_pos - m_neg)     (higher-is-better)
      BS = (m_neg - m_baseline) / (m_neg - m_pos)     (lower-is-better)

  Where the baseline lands in the [neg_control, pos_control] range, per
  metric. 1.0 = matches pos_control (perfect); 0.0 = matches neg_control
  (no signal). Computed by ``bs_per_pert``. The baseline predictor is
  configurable; positive control defaults to Tech-duplicate, negative
  control to Zero.

* **Captured Fraction (CF):**
      CF = (m_pred - m_base) / (m_pos - m_neg)

  Improvement of a predictor over the baseline, normalized by the
  pos/neg control gap. Computed by ``cf_per_pert``.

Both functions return DataFrames keyed on (bin, ko, metric) and attach a
``drf`` column (via ``compute_drf``) used by ``filter_drf`` to drop
rows whose dynamic range is too small to be meaningful.

Per-pert metric inventory
=========================
``METRICS_CONFIG`` and ``REAL_DATA_METRICS_CONFIG`` list the ~70 specs
the current benchmark computes. They're generated by
``expand_metrics_config`` from:

  * ``BASES`` — 8 row-level families
    (mse, mae, pearson, r2, r2_centered, ccc, spearman, frac_correct_direction).
  * ``SUFFIXES`` — gene-subset / weighting modifiers
    (``_weighted``, ``_var_weighted``, ``_within``, ``_outside``,
    ``_across_TF_perturbations``, ``_top_200_*``, ``_top_1000_*``,
    plus bio-relation variants ``_go_*`` / ``_ppi_*`` / ``_pathway_*`` /
    ``_tf_target_*`` for the real-data config).
  * ``METRIC_SELECTION`` — which (base, suffix) combinations to materialize.

Plus 9 standalone specs (fold_change_gap, var_ratio_log_error,
pds_cosine/l2/l1, effect_size_auroc, cosine_rank, gsea_up, gsea_down).

Use ``list_all_metrics()`` for a DataFrame view of the live inventory.
``main_benchmark_metrics()`` filters to the ~17-metric headline subset
(see ``MAIN_BENCHMARK_METRIC_NAMES``).

Architecture
============
::

    run_pipeline.py
        -> cmd_bs / cmd_cf / cmd_metrics
        -> meta_metrics.bs_per_pert / cf_per_pert / compute_per_pert_metrics
        -> meta_metrics._compute_per_pert_via_kernels  (dispatch by spec.base)
        -> metric_kernels.* (torch primitives; full literature library)

Filters: ``filter_drf``, ``filter_pos_ge_neg``, ``filter_min_genes``
(post-hoc DataFrame transforms surfaced as ``run_pipeline.py`` CLI flags).
"""

