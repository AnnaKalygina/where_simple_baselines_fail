DEFAULT_BASELINE_PER_SCENARIO: Dict[str, str] = {
    "UnseenPert":  "Mean-over-perturbations",
    "UnseenCell":  "Mean-over-cell-types",
    "UnseenBoth":  "Mean-over-perturbations-and-cell-types",
    "UnseenPair":  "Two-way-mean",
    "UnseenDose":  "Scaled-delta",
    "UnseenCombo": "Additive",
}

NEGATIVE_CONTROL: str = "Zero"
# The positive control / ceiling is the INTERPOLATED duplicate, not the raw
# Tech-duplicate. The interp blends the second-half tech-dup toward the mean
# baseline by per-gene DEG significance, so by design it is never beaten by the
# mean (matches the upstream Perturbation-Models-Outperform-Baselines design).
# The raw Tech-duplicate saturates on weak-effect datasets (e.g. frangieh21,
# half-split corr ~0.17), which would invert the BS/CF dynamic range.
POSITIVE_CONTROL: str = "Interp-duplicate"

# ── Empirically-hardest BS reference baseline (Task 4) ───────────────────────
# Candidate SIMPLE baselines per regime. The "hardest" — the best-scoring of these
# on the kept (E-test) perturbations — is used as m_base so BS/CF score against the
# toughest simple baseline the regime structurally allows.
CANDIDATE_BASELINES_PER_SCENARIO: Dict[str, List[str]] = {
    "UnseenPert":  ["Mean-over-perturbations", "Mean-over-perturbations-and-cell-types",
                    "TargetScaling", "Mean+TargetScaling"],
    "UnseenCell":  ["Mean-over-cell-types", "Mean-over-perturbations-and-cell-types",
                    "TargetScaling", "Mean+TargetScaling"],
    "UnseenBoth":  ["Mean-over-perturbations-and-cell-types", "TargetScaling", "Mean+TargetScaling"],
    "UnseenPair":  ["Two-way-mean", "Mean-over-perturbations", "Mean-over-cell-types",
                    "Mean-over-perturbations-and-cell-types", "TargetScaling", "Mean+TargetScaling"],
    "UnseenDose":  ["Scaled-delta", "TargetScaling"],
    "UnseenCombo": ["Additive", "Matching-mean", "TargetScaling"],
}
# Calibrated metric subset for ranking candidates (mixed directions handled by
# per-metric ranking; mirrors the figure aggregate set).
HARDEST_BASELINE_METRICS: List[str] = [
    "mse_weighted", "pearson_weighted", "ccc_weighted", "gsea_up", "gsea_down",
]


def hardest_baseline(dataset: str, scenario: str, *,
                     filter_kind: str = "etest", return_table: bool = False):
    """Empirically hardest (best-scoring) SIMPLE baseline for (dataset, scenario).

    Ranks ``CANDIDATE_BASELINES_PER_SCENARIO`` by average per-metric rank over
    ``HARDEST_BASELINE_METRICS`` on the filter-kept perturbations, reading the pooled
    ``metrics.csv`` (so the candidates must already be scored). Direction-aware
    ranking handles mixed higher/lower-is-better metrics. Falls back to
    ``DEFAULT_BASELINE_PER_SCENARIO`` if no candidate is scored yet.

    return_table=True -> (winner, {candidate: avg_rank}); else just the winner name.
    """
    import pandas as pd
    from benchmark.config import RESULTS_DIR
    from benchmark import signal_filters as sf

    default = DEFAULT_BASELINE_PER_SCENARIO[scenario]
    cands = CANDIDATE_BASELINES_PER_SCENARIO.get(scenario, [default])
    mpath = RESULTS_DIR / dataset / scenario / "pooled" / "metrics.csv"
    if not mpath.exists():
        log.warning("hardest_baseline: no pooled metrics at %s; default %s", mpath, default)
        return (default, {}) if return_table else default
    df = pd.read_csv(mpath, usecols=["predictor", "ko_name", "bin_name", "metric", "value"])
    df = df[df["ko_name"] != "_global_"]
    present = [c for c in cands if c in set(df["predictor"])]
    if not present:
        log.warning("hardest_baseline: no candidate scored for %s/%s; default %s",
                    dataset, scenario, default)
        return (default, {}) if return_table else default
    try:
        df = sf.restrict_by_keys(df, sf.pass_keys(dataset, filter_kind))
    except Exception as e:  # signal stats missing -> rank on all perts
        log.warning("hardest_baseline: filter %s unavailable for %s (%s); ranking on all perts",
                    filter_kind, dataset, e)
    specs = {s.name: s for s in main_benchmark_metrics()}
    metrics = [m for m in HARDEST_BASELINE_METRICS if m in specs and (df["metric"] == m).any()]
    rank_sum = {c: 0.0 for c in present}; nmet = 0
    for m in metrics:
        med = df[df["metric"] == m].groupby("predictor")["value"].median()
        med = med[[c for c in present if c in med.index]]
        if med.empty:
            continue
        order = med.sort_values(ascending=not specs[m].higher_is_better)  # best first
        for rk, c in enumerate(order.index, start=1):
            rank_sum[c] += rk
        nmet += 1
    if nmet == 0:
        winner = default if default in present else present[0]
        return (winner, {}) if return_table else winner
    avg_rank = {c: rank_sum[c] / nmet for c in present}
    winner = min(avg_rank, key=avg_rank.get)
    return (winner, avg_rank) if return_table else winner


def _resolve_baseline_name(baseline_predictor, dataset, scenario):
    """Resolve the BS/CF reference baseline: an explicit predictor name, the
    'auto_hardest' sentinel (-> hardest_baseline), or None -> scenario default."""
    if baseline_predictor == "auto_hardest":
        return hardest_baseline(dataset, scenario)
    return baseline_predictor or DEFAULT_BASELINE_PER_SCENARIO[scenario]


def _compute_per_pert_via_kernels(
    deltas_pred: np.ndarray,
    deltas_gt: np.ndarray,
    metric_specs: List["MetricSpec"],
    *,
    weights: Optional[np.ndarray] = None,
    deg_mask: Optional[np.ndarray] = None,
    deg_directions: Optional[np.ndarray] = None,
    device: str = "cpu",
    pair_keep: Optional[np.ndarray] = None,
    missing_genes: str = "fill_missing_genes_with_zero",
):
    """Compute per-(bin, ko, metric) values via torch metric kernels.

    deltas_pred, deltas_gt: (n_bins, n_kos, n_genes) float arrays.
    weights, deg_mask, deg_directions: (n_bins, n_kos, n_genes) per-pert tensors.

    ``missing_genes`` controls how a gene the predictor did NOT emit (NaN in
    ``deltas_pred``) is handled, for any perturbation the predictor DID predict
    (a row with >=1 non-NaN gene):
      * ``fill_missing_genes_with_zero`` (default) — the missing gene is scored
        as a zero delta (== the control profile in our Δ-vs-control frame; the
        ``nan_to_num`` below already supplies the 0 value, so the whole panel is
        scored). All methods are then evaluated on an identical gene set.
      * ``drop_missing_genes`` — the missing gene is excluded from the metric
        (Miller et al.'s behavior; scores the predictor on its own gene subset).
    A perturbation with NO predicted genes (all-NaN row) is SKIPPED in either
    mode (never imputed) — that is the perturbation axis, handled by coverage.

    NB: ``drop_missing_genes`` is exact only for the maskable per-gene metrics
    (mse/mae/pearson/r2/ccc/frac_correct_direction/top_k). The global /
    discrimination kernels (``pds_*``, ``cosine_rank``, ``gsea_*``,
    ``var_ratio_log_error``) read the ``nan_to_num``'d tensor without the gene
    mask, so they zero-impute regardless of mode.

    Returns a long-format DataFrame with columns:
        bin_idx, ko_idx, metric, value, n_genes_valid, n_genes_native.
    """
    import pandas as pd
    import torch
    from benchmark import metric_kernels as mk

    pred_t = torch.from_numpy(np.nan_to_num(deltas_pred).astype(np.float32))
    tgt_t = torch.from_numpy(deltas_gt.astype(np.float32))

    n_bins, n_kos, n_genes = pred_t.shape
    # Flatten (bin, ko) → row
    pred2 = pred_t.reshape(-1, n_genes)
    tgt2 = tgt_t.reshape(-1, n_genes)
    n_rows = pred2.shape[0]
    ko_axis = np.arange(n_kos)
    bin_axis = np.arange(n_bins)
    bi_per_row = np.repeat(bin_axis, n_kos)
    ki_per_row = np.tile(ko_axis, n_bins)

    native_valid = ~np.isnan(deltas_pred).reshape(n_rows, n_genes)  # genes the model emitted
    row_predicted = native_valid.any(axis=1)                        # perturbation predicted at all?
    n_native = native_valid.sum(axis=1)                             # native coverage per (bin, ko)
    if missing_genes == "fill_missing_genes_with_zero":
        # Score the full panel for any predicted perturbation; missing genes were
        # nan_to_num'd to 0 == control == zero delta. All-NaN rows score nothing.
        base_mask = np.broadcast_to(row_predicted[:, None], native_valid.shape)
    elif missing_genes == "drop_missing_genes":
        base_mask = native_valid
    else:
        raise ValueError(
            f"unknown missing_genes mode {missing_genes!r}; expected "
            "'fill_missing_genes_with_zero' or 'drop_missing_genes'"
        )
    nan_mask = torch.from_numpy(np.ascontiguousarray(base_mask))

    # UnseenPair: restrict scoring to the held-out test PAIRS. Non-test (bin, ko)
    # rows in the test rectangle get an all-False mask → n_valid==0 → skipped, so
    # the predictor is scored only on the pairs it was actually asked to predict.
    if pair_keep is not None:
        keep_rows = torch.from_numpy(np.asarray(pair_keep, dtype=bool).reshape(n_rows))
        nan_mask = nan_mask & keep_rows[:, None]

    rows: List[dict] = []
    for spec in metric_specs:
        # Pick the kernel for this metric
        name = spec.name
        gene_mask = nan_mask
        # Top-k per-row filter
        if spec.top_k is not None:
            abs_tgt = tgt2.abs()
            topk_idx = abs_tgt.topk(spec.top_k, dim=1).indices
            topk_mask = torch.zeros_like(gene_mask)
            topk_mask.scatter_(1, topk_idx, True)
            gene_mask = gene_mask & topk_mask

        # Compute the metric
        try:
            if spec.base == "mse":
                err = mk.sq_err(pred2, tgt2)
                if spec.suffix == "_weighted" and weights is not None:
                    w = torch.from_numpy(weights.reshape(n_rows, n_genes))
                    vals = mk.row_weighted_mean(err, w, gene_mask)
                else:
                    vals = mk.row_masked_mean(err, gene_mask, min_count=1)
            elif spec.base == "mae":
                err = mk.abs_err(pred2, tgt2)
                if spec.suffix == "_weighted" and weights is not None:
                    w = torch.from_numpy(weights.reshape(n_rows, n_genes))
                    vals = mk.row_weighted_mean(err, w, gene_mask)
                else:
                    vals = mk.row_masked_mean(err, gene_mask, min_count=1)
            elif spec.base in ("pearson", "r2", "r2_centered", "ccc", "spearman"):
                # Per-gene DEG weights for the `_weighted` variants (None otherwise);
                # the correlation kernels take them directly (weighted moments).
                # Previously these were called WITHOUT weights, so `_weighted` was a
                # silent no-op for correlation metrics — fixed here.
                w_corr = (torch.from_numpy(weights.reshape(n_rows, n_genes))
                          if spec.suffix == "_weighted" and weights is not None else None)
                if spec.base == "pearson":
                    vals = mk.row_pearson(pred2, tgt2, gene_mask, w_corr)
                elif spec.base in ("r2", "r2_centered"):
                    # Headline "r2" uses the CENTERED + (-1)-clamped formula to match
                    # Miller's sklearn r2_score (the uncentered row_r2 is retained as
                    # a primitive but no longer the reported metric).
                    vals = mk.row_r2_centered(pred2, tgt2, gene_mask, w_corr)
                elif spec.base == "ccc":
                    vals = mk.row_ccc(pred2, tgt2, gene_mask, w_corr)
                else:  # spearman
                    vals = mk.row_spearman(pred2, tgt2, gene_mask, w_corr)
            elif spec.base == "frac_correct_direction":
                if deg_directions is None:
                    continue
                de_dir = torch.from_numpy(deg_directions.reshape(n_rows, n_genes))
                vals = mk.row_frac_correct_direction(pred2, de_dir, gene_mask)
            elif name == "fold_change_gap":
                vals = mk.row_fold_change_gap(pred2, tgt2, gene_mask)
            elif name in {"pds_cosine", "pds_l2", "pds_l1"}:
                # PDS is a GLOBAL score (one float per bin-batch of perts), not
                # per-pert. Emit one row per bin with bin_idx and ko_idx=-1 so
                # downstream BS/CF can still consume it.
                metric_name = name.replace("pds_", "")
                # Computed per-bin: pds expects (K, G).
                for bi in range(n_bins):
                    v = mk.pds(pred_t[bi], tgt_t[bi], metric=metric_name)
                    rows.append({
                        "bin_idx": int(bi), "ko_idx": -1,
                        "metric": name, "value": float(v),
                        "n_genes_valid": int(n_genes),
                        "n_genes_native": int(n_genes),
                    })
                continue
            elif name == "cosine_rank":
                # Per-pert: cosine_rank expects (K, G). Apply per-bin.
                vals_per_bin = []
                for bi in range(n_bins):
                    v = mk.cosine_rank(pred_t[bi], tgt_t[bi])
                    vals_per_bin.append(v)
                vals = torch.cat(vals_per_bin, dim=0) if vals_per_bin else torch.zeros(0)
            elif name == "effect_size_auroc":
                vals = mk.effect_size_auroc(pred2, tgt2)
            elif name == "var_ratio_log_error":
                # GLOBAL: returns one float across all (bin, ko, gene). Emit one row.
                v = mk.var_ratio_log_error(pred_t.reshape(-1, n_genes), tgt_t.reshape(-1, n_genes))
                rows.append({
                    "bin_idx": -1, "ko_idx": -1,
                    "metric": name, "value": float(v),
                    "n_genes_valid": int(n_genes),
                    "n_genes_native": int(n_genes),
                })
                continue
            elif name == "gsea_up":
                if deg_mask is None:
                    continue
                dm = torch.from_numpy(deg_mask.reshape(n_rows, n_genes))
                vals = mk.row_gsea_up(pred2, tgt2, dm)
            elif name == "gsea_down":
                if deg_mask is None:
                    continue
                dm = torch.from_numpy(deg_mask.reshape(n_rows, n_genes))
                vals = mk.row_gsea_down(pred2, tgt2, dm)
            else:
                continue
        except Exception as e:  # pragma: no cover
            log.warning("metric %r failed on group (n_rows=%d, n_genes=%d); skipping: %s",
                        name, n_rows, n_genes, e)
            continue

        vals_np = vals.cpu().numpy()
        n_valid = gene_mask.sum(dim=1).cpu().numpy()
        for row_idx in range(n_rows):
            v = float(vals_np[row_idx])
            if np.isnan(v):
                continue
            # A row with zero valid (non-NaN, mask-passing) genes is an
            # UNDEFINED metric — the predictor emitted nothing for this (bin, ko).
            # The row kernels otherwise return a misleadingly "perfect" value
            # (mse→0, r2→1) for an all-masked row; skip it so a model is never
            # credited for a perturbation it could not represent.
            if n_valid[row_idx] == 0:
                continue
            rows.append({
                "bin_idx": int(bi_per_row[row_idx]),
                "ko_idx": int(ki_per_row[row_idx]),
                "metric": name,
                "value": v,
                "n_genes_valid": int(n_valid[row_idx]),
                "n_genes_native": int(n_native[row_idx]),
            })

    return pd.DataFrame(rows)


def compute_per_pert_metrics(
    dataset: str,
    scenario: str,
    fold: int,
    predictor_name: str,
    metric_specs: Optional[List["MetricSpec"]] = None,
    *,
    store=None,
    missing_genes: str = "fill_missing_genes_with_zero",
):
    """Compute per-(test_ko, test_bin, metric) values for one predictor.

    ``missing_genes`` — see ``_compute_per_pert_via_kernels`` (gene-axis handling
    of predictions the model did not emit).

    Returns a long-format DataFrame with columns:
        dataset, scenario, fold, predictor, ko_name, bin_name, metric,
        value, n_genes_valid, n_genes_native.
    """
    import pandas as pd
    from benchmark.data_loader import DatasetStore
    from benchmark.predictors.base import load_predictions

    store = store or DatasetStore(dataset)
    bundle = load_predictions(
        dataset, scenario, fold, predictor_name,
        store=store,
        # Allow gene subset for DL adapters (any non-DL predictor will pass
        # exact alignment anyway).
        require_exact_genes=(predictor_name not in {"scGPT", "GEARS", "PRESAGE"}),
    )

    specs = metric_specs if metric_specs is not None else main_benchmark_metrics()

    # Align ground truth to the bundle's bin/ko axes (in canonical order).
    # Evaluation GT is the first-half mean (matches Miller's first-half baseline);
    # predictors train on store.all_deltas, but are SCORED against this.
    gt_full = store.first_half_deltas  # (n_bins, n_kos, n_genes)
    weights_full = store.per_pert_weights
    deg_directions_full = store.deg_directions

    bin_idx = bundle.bin_index_in_store
    ko_idx = bundle.ko_index_in_store
    bin_idx_valid = bin_idx[bin_idx >= 0]
    ko_idx_valid = ko_idx[ko_idx >= 0]
    if len(bin_idx_valid) == 0 or len(ko_idx_valid) == 0:
        return pd.DataFrame(columns=[
            "dataset", "scenario", "fold", "predictor", "ko_name",
            "bin_name", "metric", "value", "n_genes_valid", "n_genes_native",
        ])

    gt = gt_full[np.ix_(bin_idx_valid, ko_idx_valid)]
    w = weights_full[np.ix_(bin_idx_valid, ko_idx_valid)]
    de_dir = deg_directions_full[np.ix_(bin_idx_valid, ko_idx_valid)]
    de_mask = store.deg_mask[np.ix_(bin_idx_valid, ko_idx_valid)]

    # Restrict the prediction to the SAME (bin, ko) positions that map into the
    # store — i.e. drop any predicted bin/ko absent from the store (e.g. a DL
    # model that emitted combos under upstream labels not present in this panel).
    # Otherwise pred carries extra rows and mismatches gt's shape. bundle.deltas
    # is in bundle's canonical order, parallel to bin_index_in_store / ko_index_in_store.
    bin_keep = bin_idx >= 0
    ko_keep = ko_idx >= 0
    pred_valid = bundle.deltas[bin_keep][:, ko_keep, :]

    # Handle the gene-subset case: project deltas onto store's gene axis.
    if pred_valid.shape[-1] != store.n_genes:
        full_pred = np.full((pred_valid.shape[0], pred_valid.shape[1], store.n_genes),
                             np.nan, dtype=np.float32)
        gene_idx = bundle.gene_index_in_store
        valid = gene_idx >= 0
        full_pred[..., gene_idx[valid]] = pred_valid[..., valid]
        pred = full_pred
    else:
        pred = pred_valid

    # Non-rectangular scenarios (UnseenPair, and UnseenBoth via its stored masks)
    # carry an explicit test-pair mask; score ONLY those cells. Gate on the mask's
    # presence rather than a hardcoded scenario name. (For UnseenBoth the predicted
    # output is already the {test_bin} × test_perts rectangle, so the sliced mask is
    # all-True and this is a no-op; the gate stays correct if that ever changes.)
    pair_keep = None
    split_info = store.split(scenario, fold)
    if split_info.test_pair_mask is not None:
        pair_keep = split_info.test_pair_mask[np.ix_(bin_idx_valid, ko_idx_valid)]

    df = _compute_per_pert_via_kernels(
        pred, gt, specs,
        weights=w, deg_mask=de_mask, deg_directions=de_dir,
        pair_keep=pair_keep, missing_genes=missing_genes,
    )
    if df.empty:
        return df
    df["dataset"] = dataset
    df["scenario"] = scenario
    df["fold"] = fold
    df["predictor"] = predictor_name
    df["ko_name"] = [bundle.ko_names[i] if i >= 0 else "_global_" for i in df["ko_idx"]]
    df["bin_name"] = [bundle.bin_names[i] if i >= 0 else "_global_" for i in df["bin_idx"]]
    return df[[
        "dataset", "scenario", "fold", "predictor", "ko_name", "bin_name",
        "metric", "value", "n_genes_valid", "n_genes_native",
    ]]


