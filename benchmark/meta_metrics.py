# ===================================================================
# DRF (Dynamic Range Fraction) -- attached as a filter column on BS/CF
# ===================================================================

def compute_drf(
    positive_values,
    negative_values,
    higher_is_better: bool,
    perfect: float,
    eps: float = 1e-6,
) -> np.ndarray:
    """Compute DRF for metric values (scalar or array).

    For higher-is-better: DRF = (pos - neg) / (perfect - neg + eps)
    For lower-is-better:  DRF = (neg - pos) / (neg + eps)

    Negative DRF indicates inverted dynamic range (positive control worse
    than negative control for that perturbation).

    Returns:
        DRF scores (unclipped).
    """
    pos = np.asarray(positive_values, dtype=np.float64)
    neg = np.asarray(negative_values, dtype=np.float64)
    if higher_is_better:
        drf = (pos - neg) / (perfect - neg + eps)
    else:
        drf = (neg - pos) / (neg - perfect + eps)
    return drf


