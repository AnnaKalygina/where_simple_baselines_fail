def bs_per_pert(
    dataset: str,
    scenario: str,
    fold: int,
    baseline_predictor: Optional[str] = None,
    metric_specs: Optional[List[MetricSpec]] = None,
    *,
    store=None,
    missing_genes: str = "fill_missing_genes_with_zero",
):
    """Per-perturbation Baseline Saturation.

    BS = (m_baseline - m_neg) / (m_pos - m_neg)

    The baseline predictor can be ANY registered Predictor; defaults to the
    MSE-optimal pick for the scenario in `DEFAULT_BASELINE_PER_SCENARIO`.
    """
    import pandas as pd
    from benchmark.data_loader import DatasetStore

    store = store or DatasetStore(dataset)
    base_name = _resolve_baseline_name(baseline_predictor, dataset, scenario)
    specs = metric_specs if metric_specs is not None else main_benchmark_metrics()

    m_neg = compute_per_pert_metrics(dataset, scenario, fold, NEGATIVE_CONTROL,
                                      specs, store=store, missing_genes=missing_genes)
    m_pos = compute_per_pert_metrics(dataset, scenario, fold, POSITIVE_CONTROL,
                                      specs, store=store, missing_genes=missing_genes)
    m_base = compute_per_pert_metrics(dataset, scenario, fold, base_name,
                                       specs, store=store, missing_genes=missing_genes)

    keys = ["dataset", "scenario", "fold", "ko_name", "bin_name", "metric"]
    df = (m_neg.rename(columns={"value": "m_neg", "n_genes_valid": "n_neg"})
                .drop(columns=["predictor"])
                .merge(m_pos[keys + ["value"]].rename(columns={"value": "m_pos"}), on=keys)
                .merge(m_base[keys + ["value"]].rename(columns={"value": "m_base"}), on=keys))

    # Annotate higher_is_better + perfect_value per metric for downstream filters.
    spec_lut = {s.name: s for s in specs}
    df["higher_is_better"] = df["metric"].map(lambda n: spec_lut[n].higher_is_better)
    df["perfect"] = df["metric"].map(lambda n: spec_lut[n].perfect_value)

    # Baseline Saturation: where in [neg_control, pos_control] does the baseline land?
    # 1.0 = matches pos_control (perfect prediction); 0.0 = matches neg_control (no signal).
    def bs_row(r):
        if r["higher_is_better"]:
            return float((r["m_base"] - r["m_neg"]) / (r["m_pos"] - r["m_neg"] + 1e-8))
        return float((r["m_neg"] - r["m_base"]) / (r["m_neg"] - r["m_pos"] + 1e-8))
    df["bs"] = df.apply(bs_row, axis=1).astype(float)

    # Add DRF for filtering downstream.
    df["drf"] = df.apply(
        lambda r: compute_drf(r["m_pos"], r["m_neg"],
                              r["higher_is_better"], r["perfect"]),
        axis=1,
    ).astype(float)
    df["baseline_predictor"] = base_name
    return df


def cf_per_pert(
    dataset: str,
    scenario: str,
    fold: int,
    predictor_name: str,
    baseline_predictor: Optional[str] = None,
    metric_specs: Optional[List[MetricSpec]] = None,
    *,
    store=None,
    missing_genes: str = "fill_missing_genes_with_zero",
):
    """Per-perturbation Captured Fraction.

    CF = (m_pred - m_base) / (m_pos - m_neg) for higher-is-better metrics
         (signs flipped for lower-is-better).
    """
    import pandas as pd
    from benchmark.data_loader import DatasetStore

    store = store or DatasetStore(dataset)
    base_name = _resolve_baseline_name(baseline_predictor, dataset, scenario)
    specs = metric_specs if metric_specs is not None else main_benchmark_metrics()

    m_neg = compute_per_pert_metrics(dataset, scenario, fold, NEGATIVE_CONTROL,
                                      specs, store=store, missing_genes=missing_genes)
    m_pos = compute_per_pert_metrics(dataset, scenario, fold, POSITIVE_CONTROL,
                                      specs, store=store, missing_genes=missing_genes)
    m_base = compute_per_pert_metrics(dataset, scenario, fold, base_name,
                                       specs, store=store, missing_genes=missing_genes)
    m_pred = compute_per_pert_metrics(dataset, scenario, fold, predictor_name,
                                       specs, store=store, missing_genes=missing_genes)

    keys = ["dataset", "scenario", "fold", "ko_name", "bin_name", "metric"]
    df = (m_neg.rename(columns={"value": "m_neg"})
                .drop(columns=["predictor", "n_genes_valid"])
                .merge(m_pos[keys + ["value"]].rename(columns={"value": "m_pos"}), on=keys)
                .merge(m_base[keys + ["value"]].rename(columns={"value": "m_base"}), on=keys)
                .merge(m_pred[keys + ["value"]].rename(columns={"value": "m_pred"}), on=keys))

    spec_lut = {s.name: s for s in specs}
    df["higher_is_better"] = df["metric"].map(lambda n: spec_lut[n].higher_is_better)
    df["perfect"] = df["metric"].map(lambda n: spec_lut[n].perfect_value)

    def bs_row(r):
        if r["higher_is_better"]:
            return float((r["m_base"] - r["m_neg"]) / (r["m_pos"] - r["m_neg"] + 1e-8))
        return float((r["m_neg"] - r["m_base"]) / (r["m_neg"] - r["m_pos"] + 1e-8))
    df["bs"] = df.apply(bs_row, axis=1).astype(float)

    def cf_row(r):
        denom = (r["m_pos"] - r["m_neg"]) if r["higher_is_better"] else (r["m_neg"] - r["m_pos"])
        num = (r["m_pred"] - r["m_base"]) if r["higher_is_better"] else (r["m_base"] - r["m_pred"])
        if abs(denom) < 1e-12:
            return float("nan")
        return float(num / denom)
    df["cf"] = df.apply(cf_row, axis=1).astype(float)

    df["drf"] = df.apply(
        lambda r: compute_drf(r["m_pos"], r["m_neg"],
                              r["higher_is_better"], r["perfect"]),
        axis=1,
    ).astype(float)

    df["predictor"] = predictor_name
    df["baseline_predictor"] = base_name
    return df


# ===================================================================
# Composable filters (post-hoc DataFrame transforms)
# ===================================================================


def filter_drf(df, threshold: float = 0.2):
    """Keep rows where DRF > threshold (dynamic range fraction).

    Requires a `drf` column (computed by `bs_per_pert` / `cf_per_pert`).
    """
    return df[df["drf"] > threshold].copy()


def filter_pos_ge_neg(df):
    """Keep rows where the positive control beats the negative control.

    For higher-is-better metrics: pos >= neg.
    For lower-is-better metrics: pos <= neg.
    """
    higher = df["higher_is_better"].astype(bool)
    keep = (higher & (df["m_pos"] >= df["m_neg"])) | (~higher & (df["m_pos"] <= df["m_neg"]))
    return df[keep].copy()


def filter_min_genes(df, min_n: int = 10):
    """Keep rows with enough valid genes."""
    return df[df.get("n_genes_valid", df.get("n_neg", 0)) >= min_n].copy()


# ===================================================================
# Per-cell-type aggregation of a BS / CF per-pert DataFrame
# ===================================================================


def overlap_perturbations(covered: Dict[str, set]) -> set:
    """The cross-predictor overlapping-perturbation set: the intersection of the
    ``(bin_name, ko_name)`` cells each predictor covers.

    ``covered`` maps predictor name -> set of covered ``(bin_name, ko_name)``
    tuples. Returns the intersection over all predictors (empty if none). Core
    helper so ``run_pipeline``, the summary builder, and
    ``scripts/overlapping_perturbations.py`` share ONE definition (scripts->core).
    """
    if not covered:
        return set()
    it = iter(covered.values())
    out = set(next(it))
    for s in it:
        out &= s
    return out


def summarize_meta_metric(
    df,
    value_col: str,
    group_cols: List[str],
    *,
    clean: bool = True,
    drf_threshold: float = 0.2,
    extra_median_cols: Optional[List[str]] = None,
):
    """Aggregate a per-pert BS/CF table to per-cell-type headline statistics.

    For every combination of ``group_cols`` (e.g. ``baseline_predictor`` +
    ``metric`` for BS; ``predictor`` + ``baseline_predictor`` + ``metric`` for
    CF) emit one row per cell type (the ``bin_name`` values) PLUS a ``combined``
    row spanning all cell types, each holding ``n / mean / median / std`` of
    ``value_col`` over the perturbation-cells in that group.

    The ``view`` column carries the cell type (e.g. ``K562``, ``RPE1``) or
    ``combined``. Single-bin datasets emit only ``combined``.

    With ``clean=True`` (the headline default) the aggregation is restricted to
    the meaningful dynamic-range subset — positive control beats negative
    (``filter_pos_ge_neg``) AND ``DRF > drf_threshold`` (``filter_drf``) — the
    same filter used for the reported figures. The raw per-pert rows in
    ``bs.csv`` / ``cf.csv`` stay unfiltered; only this summary is filtered.

    Global (non per-cell-type) metric rows — the ``_global_`` ``ko_name`` /
    ``bin_name`` sentinels written for whole-panel metrics like ``pds_cosine``
    and ``var_ratio_log_error`` — are dropped, since they cannot be resolved per
    cell type. They remain available in the raw per-pert CSV.
    """
    import pandas as pd

    real = df[(df["bin_name"] != "_global_") & (df["ko_name"] != "_global_")].copy()
    bins = sorted(b for b in real["bin_name"].dropna().unique())

    work = real
    if clean:
        work = filter_pos_ge_neg(work)
        work = filter_drf(work, drf_threshold)

    rows: List[dict] = []
    for keys, g in work.groupby(group_cols, dropna=False):
        keys = keys if isinstance(keys, tuple) else (keys,)
        keymap = dict(zip(group_cols, keys))
        views = ([(b, g[g["bin_name"] == b]) for b in bins]
                 if len(bins) > 1 else [])
        views.append(("combined", g))
        for view, sub in views:
            v = sub[value_col].astype(float)
            n = int(v.notna().sum())
            out = {
                **keymap,
                "view": view,
                "n": n,
                "mean": float(v.mean()) if n else float("nan"),
                "median": float(v.median()) if n else float("nan"),
                "std": float(v.std()) if n else float("nan"),
            }
            # Optional per-group medians of side columns (e.g. n_genes_valid,
            # n_genes_native) for the raw-metrics distribution summary.
            for col in (extra_median_cols or ()):
                out[col] = (float(sub[col].median())
                            if n and col in sub.columns else float("nan"))
            rows.append(out)
    return pd.DataFrame(rows)


def summarize_metric_distributions(
    dataset: str,
    scenario: str,
    *,
    store=None,
    metric_specs: Optional[List["MetricSpec"]] = None,
):
    """Aggregate per-perturbation metrics into one distribution row per
    ``(predictor, metric, missing_genes, pert_set, view)``.

    Emits BOTH missing-gene modes (``fill_missing_genes_with_zero`` and
    ``drop_missing_genes``) and BOTH perturbation sets (``full`` = each
    predictor's own coverage; ``overlapping`` = the cross-method shared set),
    each describing the across-perturbation distribution with ``mean / median /
    std`` plus ``n_perturbations`` and the median ``n_genes`` / ``n_genes_native``.
    ``view`` is the cell type (multi-bin datasets) or ``combined``.

    Predictors and folds are discovered from the pooled ``metrics.csv`` (the
    canonical record of what was scored), so the predictor pool and the overlap
    set match ``scripts/overlapping_perturbations.py``. Per-pert metrics are
    recomputed for BOTH modes (cheap — runs on pseudobulk deltas), so the summary
    is independent of whichever mode the on-disk ``metrics.csv`` was written in.

    Returns an empty DataFrame if no pooled metrics / predictions are present.
    """
    import pandas as pd
    from benchmark.data_loader import DatasetStore
    from benchmark.config import results_pooled_dir, existing_predictions_path

    store = store or DatasetStore(dataset)
    specs = metric_specs if metric_specs is not None else main_benchmark_metrics()

    pooled = results_pooled_dir(dataset, scenario) / "metrics.csv"
    if not pooled.exists():
        return pd.DataFrame()
    pooled_df = pd.read_csv(pooled)
    if pooled_df.empty or "predictor" not in pooled_df.columns:
        return pd.DataFrame()
    predictors = sorted(pooled_df["predictor"].astype(str).unique())
    folds = sorted(int(f) for f in pooled_df["fold"].dropna().unique())

    MODES = ("fill_missing_genes_with_zero", "drop_missing_genes")
    per: List = []
    covered: Dict[str, set] = {}
    for p in predictors:
        for mode in MODES:
            parts = []
            for fold in folds:
                if existing_predictions_path(dataset, p, scenario, fold) is None:
                    continue
                try:
                    d = compute_per_pert_metrics(dataset, scenario, fold, p, specs,
                                                 store=store, missing_genes=mode)
                except Exception as e:
                    log.warning("per-pert metrics failed for %s/%s/fold%s/%s (%s mode); "
                                "skipping: %s", dataset, scenario, fold, p, mode, e)
                    continue
                if not d.empty:
                    parts.append(d)
            if not parts:
                continue
            dd = pd.concat(parts, ignore_index=True)
            dd["missing_genes"] = mode
            per.append(dd)
            if mode == MODES[0]:  # coverage is mode-independent; record once
                covered[p] = {
                    (str(b), str(k))
                    for b, k in zip(dd["bin_name"], dd["ko_name"])
                    if str(k) != "_global_" and str(b) != "_global_"
                }
    if not per:
        return pd.DataFrame()

    allp = pd.concat(per, ignore_index=True)
    overlap = overlap_perturbations(covered)
    pert = list(zip(allp["bin_name"].astype(str), allp["ko_name"].astype(str)))
    full = allp.copy()
    full["pert_set"] = "full"
    ov = allp[[pk in overlap for pk in pert]].copy()
    ov["pert_set"] = "overlapping"
    both = pd.concat([full, ov], ignore_index=True)

    summ = summarize_meta_metric(
        both, "value",
        ["predictor", "metric", "missing_genes", "pert_set"],
        clean=False,
        extra_median_cols=["n_genes_valid", "n_genes_native"],
    )
    if summ.empty:
        return summ
    summ = summ.rename(columns={"n": "n_perturbations", "n_genes_valid": "n_genes"})
    summ.insert(0, "dataset", dataset)
    summ.insert(1, "scenario", scenario)
    cols = ["dataset", "scenario", "predictor", "metric", "missing_genes",
            "pert_set", "view", "n_perturbations", "mean", "median", "std",
            "n_genes", "n_genes_native"]
    return summ[[c for c in cols if c in summ.columns]]

