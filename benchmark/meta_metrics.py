@dataclass
class MetricSpec:
    """Specification for a single per-perturbation metric."""
    name: str
    higher_is_better: bool
    perfect_value: float
    base: str = ""
    suffix: str = ""
    needs_per_ko: bool = False
    needs_weights: bool = False
    tf_only: bool = False
    top_k: Optional[int] = None
    gene_set: str = "all"
    min_n_genes_accounted: int = 0
    category: str = ""
    in_main_benchmark: bool = False


