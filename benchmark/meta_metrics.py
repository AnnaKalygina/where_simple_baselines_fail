def expand_metrics_config(
    selection: Optional[Dict[str, List[str]]] = None,
) -> List[MetricSpec]:
    """Build METRICS_CONFIG from base x suffix selection + standalone."""
    if selection is None:
        selection = METRIC_SELECTION

    specs: List[MetricSpec] = []

    for base_name, suffix_names in selection.items():
        hib, perfect, cat = BASES[base_name]
        for sx_name in suffix_names:
            sx = SUFFIXES[sx_name]
            gene_set = sx.mask_key if sx.mask_key is not None else "all"
            min_ng = 5 if cat == "direction" else 0
            tf_only = sx.tf_only or (cat == "direction")
            metric_name = f"{base_name}{sx_name}"
            specs.append(MetricSpec(
                name=metric_name,
                higher_is_better=hib,
                perfect_value=perfect,
                base=base_name,
                suffix=sx_name,
                tf_only=tf_only,
                gene_set=gene_set,
                top_k=sx.top_k,
                needs_weights=sx.weighted or sx.var_weighted,
                min_n_genes_accounted=min_ng,
                category=cat,
                in_main_benchmark=metric_name in MAIN_BENCHMARK_METRIC_NAMES,
            ))

    standalone = [
        MetricSpec("fold_change_gap", False, 0.0, category="error"),
        MetricSpec("var_ratio_log_error", False, 0.0, needs_per_ko=True, category="distributional"),
        MetricSpec("pds_cosine", True, 1.0, needs_per_ko=True, category="discrimination"),
        MetricSpec("pds_l2", True, 1.0, needs_per_ko=True, category="discrimination"),
        MetricSpec("pds_l1", True, 1.0, needs_per_ko=True, category="discrimination"),
        MetricSpec("effect_size_auroc", True, 1.0, category="discrimination"),
        MetricSpec("cosine_rank", False, 0.0, category="discrimination"),
        MetricSpec("gsea_up", True, 1.0, category="enrichment"),
        MetricSpec("gsea_down", True, 1.0, category="enrichment"),
    ]
    for s in standalone:
        s.in_main_benchmark = s.name in MAIN_BENCHMARK_METRIC_NAMES
    specs.extend(standalone)

    return specs


def main_benchmark_metrics(
    specs: Optional[List[MetricSpec]] = None,
) -> List[MetricSpec]:
    """Return the headline ~17-metric subset (entries with in_main_benchmark=True).

    Pass `specs=None` to filter `METRICS_CONFIG`; pass an alternate list (e.g.,
    `REAL_DATA_METRICS_CONFIG`) to filter that one instead.
    """
    return [s for s in (specs if specs is not None else METRICS_CONFIG)
            if s.in_main_benchmark]


METRICS_CONFIG: List[MetricSpec] = expand_metrics_config()


def list_all_metrics(
    specs: Optional[List[MetricSpec]] = None,
):
    """Return the per-pert metric inventory as a pandas DataFrame.

    Columns: name, base, suffix, category, higher_is_better, perfect_value,
             needs_per_ko, needs_weights, selected_in_main_benchmark.

    Pass `specs=None` to introspect `METRICS_CONFIG` (default); pass
    `REAL_DATA_METRICS_CONFIG` to introspect the real-data inventory.
    """
    import pandas as pd
    chosen = specs if specs is not None else METRICS_CONFIG
    rows = [{
        "name": s.name,
        "base": s.base,
        "suffix": s.suffix,
        "category": s.category,
        "higher_is_better": s.higher_is_better,
        "perfect_value": s.perfect_value,
        "needs_per_ko": s.needs_per_ko,
        "needs_weights": s.needs_weights,
        "selected_in_main_benchmark": s.in_main_benchmark,
    } for s in chosen]
    return pd.DataFrame(rows)


